CREATE TABLE jobs (
    created_date DATE,
    job_title TEXT,
    company TEXT,
    salary TEXT,
    address TEXT,
    link_description TEXT,
    city VARCHAR(50),
    district VARCHAR(50),
    min_salary FLOAT,
    max_salary FLOAT,
    salary_unit VARCHAR(10),
    tag TEXT,
    job_description TEXT,
    time_published TEXT
);

CREATE TABLE jobs_sent (
    created_date DATE,
    job_title TEXT,
    company TEXT,
    salary TEXT,
    address TEXT,
    link_description TEXT,
    city VARCHAR(50),
    district VARCHAR(50),
    min_salary FLOAT,
    max_salary FLOAT,
    salary_unit VARCHAR(10),
    tag TEXT,
    job_description TEXT,
    time_published TEXT
);


CREATE TABLE technologies (
	name TEXT
);

CREATE TABLE categories (
    name TEXT,
    group_cat TEXT
);

SELECT 
    t.name AS technology_name,
    COUNT(DISTINCT j.job_title) AS total_jobs
FROM technologies AS t
JOIN jobs AS j 
    ON j.job_title REGEXP CONCAT('\\b', t.name, '\\b')
GROUP BY t.name
HAVING COUNT(DISTINCT j.job_title) > 0
ORDER BY total_jobs DESC;

